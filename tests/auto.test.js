test("séries : une ronde n'est consultée que si la précédente existe", async () => {
  const root = workspace({ saison: "USHL21", types: ["series"] });
  const lm = LM["USHL21PLF-Round4-Schedule.html"];
  const pending = r => ({ body: `<HTML><TITLE>USHL21PLF League Schedule</TITLE>\n<HTML><BODY><H2>Season Schedule</H2>\nDay 1 <BR>\n 1   MONTREAL at TORONTO${r}<BR>\n</BODY></HTML>`, lm });
  const files = { "USHL21PLF-Round1-Schedule.html": pending(1), "USHL21PLF-Round2-Schedule.html": pending(2), "USHL21PLF-Round3-Schedule.html": pending(3) };
  for (const f of fs.readdirSync(DIR).filter(f => f.endsWith(".html"))) files[f] = { body: real(f), lm: LM[f] };
  const s = site(files);
  const r = await run(root, s, "2026-07-05T05:00:00Z");
  assert.deepStrictEqual(r.nouveaux, [1, 2, 3, 4, 5, 6, 7].map(i => "USHL21-S4-" + i));
  const ms = readIndex(root).saisons.USHL21.matchs;
  assert.deepStrictEqual(ms.map(m => m.tr), ["approx", "approx", "approx", "approx", "approx", "approx", "exact"]);
  assert.strictEqual(ms[6].d, "dimanche, juin 28 2026");
  assert.strictEqual(loadGame(root, ms[0].src).trios.source, BASE + "USHL21PLFLines.html");
  // aucune ronde 5 n'est demandée
  assert.ok(!s.calls.some(c => /Round5/.test(c.name)));
});

test("import d'une saison archivée : séries seulement, la saison en cours ne change pas", async () => {
  const root = workspace({ archive: BASE + "archives/{saison}/" });
  const lm = LM["USHL21PLF-Round4-Schedule.html"];
  const pending = r => ({ body: `<HTML><TITLE>USHL21PLF League Schedule</TITLE>\n<HTML><BODY><H2>Season Schedule</H2>\nDay 1 <BR>\n 1   MONTREAL at TORONTO${r}<BR>\n</BODY></HTML>`, lm });
  const files = { "USHL22Schedule.html": { body: seasonSchedule(0), lm: "Sun, 18 Oct 2026 21:42:28 GMT" } };
  [1, 2, 3].forEach(r => { files[`archives/USHL21/USHL21PLF-Round${r}-Schedule.html`] = pending(r); });
  for (const f of fs.readdirSync(DIR).filter(f => f.endsWith(".html"))) files["archives/USHL21/" + f] = { body: real(f), lm: LM[f] };
  const s = site(files);
  await run(root, s, "2026-10-19T12:05:00Z");
  const r = await run(root, s, "2026-10-19T12:30:00Z", { archive: "USHL21" });
  assert.strictEqual(r.saison, "USHL21"); assert.strictEqual(r.nouveaux.length, 7);
  const idx = readIndex(root);
  assert.strictEqual(idx.saison, "USHL22");
  assert.strictEqual(idx.saisons.USHL21.base, BASE + "archives/USHL21/");
  assert.ok(!s.calls.some(c => /archives\/USHL21\/USHL21Schedule/.test(c.name)), "pas de saison régulière dans une archive");
  // le passage normal suivant reste sur la saison en cours
  const r2 = await run(root, s, "2026-10-19T12:50:00Z");
  assert.strictEqual(r2.saison, "USHL22"); assert.strictEqual(r2.modifie, false);
});

