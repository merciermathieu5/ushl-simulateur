/* ---------- Faux site : fichiers en mémoire, « Last-Modified » et réponses 304 ---------- */
const BASE = "https://ligue.test/USHL-pro/";
function site(files) {
  const calls = [];
  const fetch = async (url, init = {}) => {
    const name = decodeURIComponent(url.slice(BASE.length)), method = init.method || "GET";
    const ims = init.headers && init.headers["If-Modified-Since"];
    calls.push({ name, method, ims });
    const f = files[name] || files["*"];
    if (!f) return new Response(method === "HEAD" ? null : "<html>Page non trouvée</html>", { status: 404 });
    // réponses particulières : HEAD refusé, pare-feu, panne
    if (method === "HEAD" && f.headStatus) return new Response(null, { status: f.headStatus });
    if (f.status) return new Response(method === "HEAD" ? null : f.body, { status: f.status });
    if (ims && Date.parse(f.lm) <= Date.parse(ims)) return new Response(null, { status: 304 });
    return new Response(method === "HEAD" ? null : f.body, { status: 200, headers: { "last-modified": f.lm } });
  };
  return { fetch, calls, files };
}
function workspace(cfg) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "ushl-auto-"));
  fs.mkdirSync(path.join(root, "data", "auto"), { recursive: true });
  fs.writeFileSync(path.join(root, "data", "auto", "config.json"), JSON.stringify(Object.assign({
    base: BASE, saison: "USHL22", stabilisationMinutes: 10, maxParPassage: 150, essaisMax: 24 }, cfg)));
  return root;
}
const run = (root, s, now, extra) => recuperer(Object.assign({ root, fetch: s.fetch, now: () => new Date(now), log: () => {}, pause: 0, saisonSuivante: false }, extra));
// Charge un fichier de match généré, comme le ferait la page
function loadGame(root, rel) {
  let rec = null;
  vm.runInNewContext(fs.readFileSync(path.join(root, rel), "utf8"), { USHL_AUTO_MATCH: r => { rec = r; } });
  return rec;
}

/* Saison régulière fictive « USHL22 » : les sept matchs de la finale, un par soirée, puis deux soirées à venir. */
const FINAL = [1, 2, 3, 4, 5, 6, 7].map(i => {
  const html = realText(`USHL21PLF-R4-${i}.html`);
  return { i, html, teams: F.summaryTeams(html) };
});
const SCORES = F.parseSchedule(realText("USHL21PLF-Round4-Schedule.html")).played;
function seasonSchedule(nPlayed, scoreOverride) {
  let s = "<HTML><TITLE>USHL22 League Schedule</TITLE>\n<!-- Generated by FHL, FHL97546490 -->\n<HTML><BODY><H2>Season Schedule</H2>\n";
  for (let d = 1; d <= 9; d++) {
    s += (d > 1 ? "<BR>" : "") + `Day ${d} <BR>\n`;
    if (d <= 7) {
      const g = FINAL[d - 1], sc = Object.assign({}, SCORES[d - 1], scoreOverride && scoreOverride[d]);
      if (d <= nPlayed) s += `<A HREF=USHL22${d}.html> ${d}   ${sc.away} ${sc.sa}  ${sc.home} ${sc.sh} \n</A>\n${sc.extra ? "(" + sc.extra + ")\n" : ""}<BR>\n`;
      else s += ` ${d}   ${g.teams.away} at ${g.teams.home}<BR>\n`;
    } else s += ` ${d}   BOSTON at TORONTO<BR>\n`;
  }
  return s + "</BODY></HTML>\n";
}
function seasonSite(nPlayed, lm, opts = {}) {
  const files = {
    "USHL22Schedule.html": { body: seasonSchedule(nPlayed, opts.scores), lm },
    "USHL22Lines.html": { body: real("USHL21PLFLines.html"), lm: opts.linesLm || lm },
    "USHL22TodayGames.html": { body: `<HTML><BODY><H2>Latest Results</H2>\n<P>Games of samedi, oct ${23 + nPlayed} 2026</P>\n<A HREF=USHL22${nPlayed}.html> ${nPlayed}   X 1  Y 2 \n</A><BR>\n</BODY></HTML>\n`, lm },
    "USHL22Rosters.html": { body: real("USHL21PLFRosters.html"), lm }
  };
  for (let d = 1; d <= nPlayed; d++) if (!(opts.missing || []).includes(d)) files[`USHL22${d}.html`] = { body: real(`USHL21PLF-R4-${(opts.swap || {})[d] || d}.html`), lm };
  return files;
}

