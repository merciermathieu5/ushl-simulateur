test("une soirée simulée : sommaire, trios du soir et liste pour l'interface", async () => {
  const root = workspace(), lm = "Sat, 24 Oct 2026 02:10:00 GMT";
  const s = site(seasonSite(1, lm));
  const r = await run(root, s, "2026-10-24T02:30:00Z");
  assert.deepStrictEqual(r.nouveaux, ["USHL22-1"]);
  const idx = readIndex(root), m = idx.saisons.USHL22.matchs[0];
  assert.deepStrictEqual({ id: m.id, j: m.j, v: m.v, l: m.l, pv: m.pv, pl: m.pl, d: m.d, tr: m.tr, src: m.src },
    { id: "USHL22-1", j: 1, v: "MONTREAL", l: "NASHVILLE", pv: 4, pl: 2, d: "samedi, oct 24 2026", tr: "exact", src: "data/auto/USHL22/USHL22-1.js" });
  const rec = loadGame(root, m.src);
  // le sommaire est conservé tel quel (espaces insécables du site compris) et se lit avec le moteur
  assert.strictEqual(rec.sommaire, realText("USHL21PLF-R4-1.html"));
  const S = api.parseSummary(rec.sommaire);
  assert.strictEqual(S.away, "MONTREAL"); assert.strictEqual(S.goals.length, 6);
  const L = api.parseLines(rec.trios.html);
  assert.deepStrictEqual(Object.keys(L.teams).sort(), ["MONTREAL", "NASHVILLE"]);
  assert.strictEqual(rec.trios.qualite, "exact"); assert.strictEqual(rec.trios.asOf, "dimanche, juin 28 2026");
  const G = api.buildGame(S, L, rec.sommaire);
  assert.ok(G.diag.away.fromLines >= 15 && G.diag.home.fromLines >= 15, "joueurs placés selon les trios");
});

