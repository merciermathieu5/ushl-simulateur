test("page anti-robot au lieu du calendrier : signalée, rien d'écrit", async () => {
  const root = workspace();
  const s = site({ "USHL22Schedule.html": { body: "<html><body><h1>Please wait while your request is being verified...</h1></body></html>", lm: "Sat, 24 Oct 2026 02:10:00 GMT" } });
  await assert.rejects(run(root, s, "2026-10-24T03:00:00Z"), e => e.antiRobot === true && /anti-robot/.test(e.message));
  assert.strictEqual(readIndex(root), null);
  // une autre page inattendue est une vraie erreur
  const s2 = site({ "USHL22Schedule.html": { body: "<html><title>Maintenance</title></html>", lm: "Sat, 24 Oct 2026 02:10:00 GMT" } });
  await assert.rejects(run(root, s2, "2026-10-24T03:00:00Z"), e => !e.antiRobot && /calendrier FHL/.test(e.message));
});

